package build

import (
	"context"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"strings"

	"github.com/tkjaer/curator/internal/model"
)

// emitAuth writes the web-server access-control files for protected galleries:
// a .htpasswd per gallery plus an nginx include or per-directory .htaccess.
func (b *Builder) emitAuth(ctx context.Context, protected []model.Gallery) error {
	if len(protected) == 0 {
		return nil
	}
	serverRoot := strings.TrimRight(b.settings["site.server_root"], "/")
	if serverRoot == "" {
		log.Printf("build: %d protected gallery(ies) present but site.server_root is unset; skipping auth files", len(protected))
		return nil
	}

	if b.settings["site.webserver"] == "apache" {
		return b.emitApache(ctx, protected, serverRoot)
	}
	return b.emitNginx(ctx, protected, serverRoot)
}

func (b *Builder) emitNginx(ctx context.Context, protected []model.Gallery, serverRoot string) error {
	var conf strings.Builder
	conf.WriteString("# Generated by Curator. Include this once inside your nginx server block:\n")
	conf.WriteString("#   include " + serverRoot + "/curator-auth.conf;\n\n")

	for _, g := range protected {
		rel := b.galleryRel(g.ID)
		if err := b.writeHtpasswd(ctx, g, rel); err != nil {
			return err
		}
		fmt.Fprintf(&conf, "location /%s {\n    auth_basic %q;\n    auth_basic_user_file %s/%s.htpasswd;\n}\n\n",
			rel, realm(g.Title), serverRoot, rel)
	}

	dest := filepath.Join(b.Cfg.OutputDir, "curator-auth.conf")
	if err := os.WriteFile(dest, []byte(conf.String()), 0o644); err != nil {
		return err
	}
	b.keep(dest)
	return nil
}

func (b *Builder) emitApache(ctx context.Context, protected []model.Gallery, serverRoot string) error {
	for _, g := range protected {
		rel := b.galleryRel(g.ID)
		if err := b.writeHtpasswd(ctx, g, rel); err != nil {
			return err
		}
		htaccess := fmt.Sprintf("AuthType Basic\nAuthName %q\nAuthUserFile %s/%s.htpasswd\nRequire valid-user\n",
			realm(g.Title), serverRoot, rel)
		dest := filepath.Join(b.Cfg.OutputDir, filepath.FromSlash(rel), ".htaccess")
		if err := os.WriteFile(dest, []byte(htaccess), 0o644); err != nil {
			return err
		}
		b.keep(dest)
	}
	return nil
}

// writeHtpasswd writes a gallery's .htpasswd. An empty file (no granted users)
// safely denies everyone, since nobody can authenticate against it.
func (b *Builder) writeHtpasswd(ctx context.Context, g model.Gallery, rel string) error {
	users, err := b.Store.GalleryAccessUsers(ctx, g.ID)
	if err != nil {
		return err
	}
	if len(users) == 0 {
		log.Printf("build: protected gallery %q has no access users; it will be inaccessible", g.Slug)
	}

	var body strings.Builder
	for _, u := range users {
		body.WriteString(u.Username + ":" + u.Hash + "\n")
	}
	dest := filepath.Join(b.Cfg.OutputDir, filepath.FromSlash(rel), ".htpasswd")
	if err := os.MkdirAll(filepath.Dir(dest), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(dest, []byte(body.String()), 0o640); err != nil {
		return err
	}
	b.keep(dest)
	return nil
}

// galleryRel is a gallery's output path relative to the site root, e.g.
// "galleries/trip/day-one/".
func (b *Builder) galleryRel(id int64) string {
	return strings.TrimPrefix(b.urlPath(id), b.site.BaseURL+"/")
}

func realm(title string) string {
	return strings.ReplaceAll(title, `"`, "'")
}
